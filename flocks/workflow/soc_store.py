"""Bounded SOC alert persistence for workflow host processes.

The workflow receives a fixed write capability. Database configuration and SQL
remain in the host; no connection settings are accepted in node inputs.
"""

from __future__ import annotations

import json
import re
import threading
import time
import uuid
from datetime import datetime
from typing import Any

from flocks.db import sync_query
from flocks.db.json_nul import escape_nul_for_json, replace_nul

MAX_ALERT_ROWS = 500
MAX_ALERT_BYTES = 2 * 1024 * 1024
_schema_lock = threading.Lock()
_schema_ready: set[str] = set()
_TRIAGE_FIELDS = (
    "has_dedup_key", "triage_source", "triage_status", "triage_attack_verdict",
    "risk_level", "report_title", "triage_report", "triage_attack_success",
    "triage_ms", "triage_error", "_triage_run_id", "_triage_persisted_at",
)


def ensure_schema() -> None:
    identity = sync_query.identity()
    if identity in _schema_ready:
        return
    with _schema_lock:
        if identity in _schema_ready:
            return
        with sync_query.connect(timeout=15) as connection:
            connection.execute(
                "SELECT pg_advisory_xact_lock(hashtext(current_schema() || ':soc-alerts-schema'))",
            ).fetchone()
            connection.execute("""CREATE TABLE IF NOT EXISTS alert_records (
                row_id TEXT PRIMARY KEY,
                rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
                record_id TEXT, asset_date TEXT NOT NULL, source_file TEXT NOT NULL,
                line_number BIGINT NOT NULL, event_time BIGINT, source_type TEXT,
                threat_name TEXT, dedup_key TEXT,
                is_duplicate INTEGER NOT NULL DEFAULT 0, record_json JSONB NOT NULL)""")
            connection.execute("""CREATE UNIQUE INDEX IF NOT EXISTS idx_alert_records_first_seen_dedup_key
                ON alert_records(dedup_key) WHERE dedup_key IS NOT NULL AND dedup_key <> ''""")
            connection.execute("CREATE INDEX IF NOT EXISTS idx_alert_records_asset_date ON alert_records(asset_date)")
            connection.execute("CREATE INDEX IF NOT EXISTS idx_alert_records_event_time ON alert_records(event_time)")
        _schema_ready.add(identity)


def _event_time(alert: dict[str, Any]) -> int:
    for key in ("time", "event_time", "timestamp", "timestamp_real", "occur_time", "created_at"):
        value = alert.get(key)
        if value in (None, ""):
            continue
        try:
            result = float(value)
            return int(result / 1000 if result > 100000000000 else result)
        except (TypeError, ValueError, OverflowError):
            pass
        try:
            return int(datetime.fromisoformat(str(value).replace("Z", "+00:00")).timestamp())
        except (ValueError, OverflowError):
            pass
        for fmt in ("%Y/%m/%d %H:%M:%S", "%Y/%m/%d %H:%M"):
            try:
                return int(datetime.strptime(str(value), fmt).timestamp())
            except (ValueError, OverflowError):
                pass
    return int(time.time())


def _first(alert: dict[str, Any], names: tuple[str, ...], default: Any = "") -> Any:
    return next((alert[name] for name in names if alert.get(name) not in (None, "")), default)


def persist_triage_alerts(alerts: list[dict[str, Any]], run_id: str, source_file: str = "") -> dict[str, Any]:
    """Atomically insert/update one bounded batch, preserving original evidence."""
    if not isinstance(alerts, list) or len(alerts) > MAX_ALERT_ROWS:
        raise ValueError(f"SOC persistence accepts at most {MAX_ALERT_ROWS} alerts per batch")
    if not isinstance(run_id, str) or not run_id or len(run_id) > 256:
        raise ValueError("SOC persistence requires a run_id of 1 to 256 characters")
    if not isinstance(source_file, str) or len(source_file) > 4096:
        raise ValueError("SOC source_file must be a string of at most 4096 characters")
    encoded = json.dumps(alerts, ensure_ascii=False, allow_nan=False, separators=(",", ":"))
    if len(encoded.encode("utf-8")) > MAX_ALERT_BYTES:
        raise ValueError(f"SOC persistence batch exceeds {MAX_ALERT_BYTES} bytes")

    persisted_at = datetime.now().isoformat()
    seen: set[str] = set()
    candidates = []
    for index, alert in enumerate(alerts, 1):
        if not isinstance(alert, dict):
            raise ValueError("Every SOC alert must be a JSON object")
        if str(alert.get("is_duplicate", "")).strip().lower() not in {"false", "0", "no", "n", "off"}:
            continue
        key = str(alert.get("dedup_key") or "").strip()
        if not key or key in seen:
            continue
        seen.add(key)
        record = {**alert, "dedup_key": key, "is_duplicate": False,
                  "_triage_run_id": run_id, "_triage_persisted_at": persisted_at}
        timestamp = _event_time(record)
        date = str(_first(record, ("asset_date", "_asset_date", "date")))
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
            date = datetime.fromtimestamp(timestamp).strftime("%Y-%m-%d")
        try:
            line = int(_first(record, ("line_number", "_line_number"), index))
        except (TypeError, ValueError):
            line = index
        candidates.append({
            "row_id": uuid.uuid4().hex,
            "record_id": str(_first(record, ("record_id", "id", "uuid", "event_id", "dedup_key"))),
            "asset_date": date,
            "source_file": str(_first(record, ("source_file", "_source_file", "file_path"), source_file or "stream_alert_triage")),
            "line_number": line, "event_time": timestamp,
            "source_type": str(_first(record, ("source_type", "_source_type", "data_source", "log_type", "vendor", "device_type"))),
            "threat_name": str(_first(record, ("threat_name", "rule_name"))),
            "dedup_key": key, "record_json": record,
        })
    # PostgreSQL rejects U+0000 in jsonb and text, and one such string would
    # fail the batch (binary evidence keeps it). The original evidence is
    # stored escaped and marked, restorably; an update of the row keeps it,
    # marker and all. The triage fields are replaced on every update (see the
    # merge below), so a marker could not follow them: they, and the columns
    # copied out of the record, only have U+0000 written as text.
    for candidate in candidates:
        record = candidate["record_json"]
        for field in _TRIAGE_FIELDS:
            if field in record:
                record[field] = replace_nul(record[field])
        candidate["record_json"] = escape_nul_for_json(record)
        for column in ("record_id", "asset_date", "source_file", "source_type", "threat_name", "dedup_key"):
            candidate[column] = replace_nul(candidate[column])
    result = {"backend": "postgres", "path": "postgres/alert_records", "table": "alert_records",
              "rows": len(candidates), "inserted_rows": 0, "updated_rows": 0, "unchanged_rows": 0}
    if not candidates:
        return result
    ensure_schema()
    # Sorted conflict keys give overlapping concurrent batches the same row
    # lock order. One set-based statement replaces per-record reads/writes.
    field_sql = ", ".join("'" + field + "'" for field in _TRIAGE_FIELDS)
    merged = f"""(alert_records.record_json - 'triage_ms' - 'triage_error') ||
        COALESCE((SELECT jsonb_object_agg(key, value) FROM jsonb_each(EXCLUDED.record_json)
                  WHERE key IN ({field_sql})), '{{}}'::jsonb) ||
        jsonb_build_object('dedup_key', EXCLUDED.dedup_key, 'is_duplicate', false)"""
    sql = f"""INSERT INTO alert_records (
        row_id, record_id, asset_date, source_file, line_number, event_time,
        source_type, threat_name, dedup_key, is_duplicate, record_json)
        SELECT row_id, record_id, asset_date, source_file, line_number, event_time,
               source_type, threat_name, dedup_key, 0, record_json
        FROM jsonb_to_recordset(?::jsonb) AS incoming(
            row_id TEXT, record_id TEXT, asset_date TEXT, source_file TEXT, line_number BIGINT,
            event_time BIGINT, source_type TEXT, threat_name TEXT, dedup_key TEXT, record_json JSONB)
        ORDER BY dedup_key
        ON CONFLICT (dedup_key) WHERE dedup_key IS NOT NULL AND dedup_key <> ''
        DO UPDATE SET is_duplicate = 0, record_json = {merged}
        WHERE (alert_records.record_json - '_triage_persisted_at') IS DISTINCT FROM
              (({merged}) - '_triage_persisted_at')
        RETURNING row_id"""
    with sync_query.connect(timeout=15) as connection:
        changed = connection.execute(sql, (json.dumps(candidates, ensure_ascii=False, allow_nan=False),)).fetchall()
    proposed_ids = {candidate["row_id"] for candidate in candidates}
    result["inserted_rows"] = sum(row["row_id"] in proposed_ids for row in changed)
    result["updated_rows"] = len(changed) - result["inserted_rows"]
    result["unchanged_rows"] = len(candidates) - len(changed)
    return result


class SOCWriteCapability:
    """Only a fixed host operation is available to trusted workflow code."""

    def __init__(self, cancel_checker=None):
        self.cancel_checker = cancel_checker

    def write_alerts(self, alerts, run_id, source_file=""):
        if self.cancel_checker and self.cancel_checker():
            raise RuntimeError("Workflow cancelled before SOC persistence")
        return persist_triage_alerts(alerts, run_id, source_file)
