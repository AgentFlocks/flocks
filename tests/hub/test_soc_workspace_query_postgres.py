async def test_alert_query_facets_and_pagination_use_pg(workspace_tool, soc_rows):
    result = await asyncio.to_thread(workspace_tool._query_alerts, {"date":"2026-09-23"}, 1, 1, "asc", True, True)
    assert result["summary"]["total"] == 3 and result["summary"]["returned"] == 1
    assert result["items"][0]["raw"]["id"] == "record-1"
    assert result["facets"]["threat_type"] == [{"value":"扫描","count":3}]


async def test_jsonb_keyword_and_detail(workspace_tool, soc_rows):
    result = await asyncio.to_thread(workspace_tool._query_alert_detail, {"row_id":"row-2"}, True, False)
    assert result["found"] and result["raw"]["id"] == "record-2"
    filtered = await asyncio.to_thread(workspace_tool._query_alerts, {"keyword":"record-2"}, 5, 0, "desc", True, False)
    assert filtered["summary"]["total"] == 1


async def test_workflow_reads_same_pg_database(workspace_tool, soc_rows):
    result = await asyncio.to_thread(workspace_tool._query_workflow, {"workflow_id":"wf"}, 10)
    assert result["stats"][0]["callCount"] == 2
    assert result["executions"][0]["id"] == "exec"


async def test_missing_tables_do_not_create_local_files(workspace_tool, tmp_path, monkeypatch):
    monkeypatch.chdir(tmp_path)
    source = await asyncio.to_thread(workspace_tool._source_info)
    assert source["socDbExists"] is False and source["workflowDbExists"] is False
    assert not list(tmp_path.rglob("*.db"))
