async def test_millisecond_raw_time_does_not_fail_detail_or_list(workspace_tool, soc_time_rows):
    """BUG-013: a raw time in milliseconds was formatted as seconds (year 32970) and failed the page."""
    detail = await asyncio.to_thread(workspace_tool._query_alert_detail, {"row_id": "row-ms"}, False, False)
    assert detail["found"]
    assert detail["summary"]["eventTime"] == _DAY_START + 2
    assert detail["summary"]["eventTimeText"] == "2001-01-01 00:00:02"
    listing = await asyncio.to_thread(workspace_tool._query_alerts, {"date": "2001-01-01"}, 10, 0, "asc", False, False)
    assert [item["rowId"] for item in listing["items"]] == ["row-ms", "row-triaged", "row-benign", "row-legacy"]


