def insert_record(index, **payload):
    with sync_query.connect() as db:
        db.execute('INSERT INTO alert_records(row_id,record_json,asset_date,event_time,source_type,threat_name) VALUES(?,?::jsonb,?,?,?,?)',
            (f'alert-{index}', json.dumps(payload), '2026-09-23', 1790121600 + index, 'ndr', 'test threat'))


def test_backfill_and_trigger_keep_facts_activity_consistent(dashboard):
    insert_record(1, triage_status='ok', triage_attack_verdict='attack', triage_attack_success='success', triage_ms='invalid')
    assert dashboard._ensure_postgres_schema()
    insert_record(2)
    with sync_query.connect() as db:
        facts = db.execute('SELECT row_key, has_triage, triage_ms FROM soc_dashboard_alert_facts ORDER BY alert_row_id').fetchall()
        assert [tuple(row) for row in facts] == [('alert-1', 1, 0), ('alert-2', 0, 0)]
        initial = db.execute('SELECT MAX(activity_id) FROM soc_dashboard_activity_events').fetchone()[0]
        db.execute("UPDATE alert_records SET record_json = ?::jsonb WHERE row_id = ?", (json.dumps({'triage_status': 'ok', 'triage_attack_verdict': 'non_attack'}), 'alert-2'))
    with sync_query.connect() as db:
        assert db.execute('SELECT MAX(activity_id) FROM soc_dashboard_activity_events').fetchone()[0] > initial
        assert db.execute('SELECT has_triage FROM soc_dashboard_alert_facts WHERE row_key = ?', ('alert-2',)).fetchone()[0] == 1
    assert dashboard._ensure_postgres_schema()
    sources = dashboard._find_postgres_sources('2026-09-23', '2026-09-23')
    assert len(sources) == 1 and sources[0].record_count == 2
    triage = dashboard._read_triage(sources)
    assert triage['totalRecords'] == 2 and triage['attackSuccess'] == 1


def test_public_stats_activity_and_workflow_payload_bounds(dashboard):
    for index in range(15): insert_record(index, triage_status='ok', triage_attack_verdict='attack', triage_attack_success='failed')
    ctx = SimpleNamespace(database=sync_query)
    stats = dashboard.get_stats(ctx, SimpleNamespace(query_params={'date':'2026-09-23','force':'true'}))
    assert stats['triage']['totalRecords'] == 15
    assert stats['denoise']['totalUnique'] == 15
    first = dashboard.get_activity(ctx, SimpleNamespace(query_params={'bootstrap':'latest'}))
    assert 'error' not in first
    insert_record(20)
    activity = dashboard.get_activity(ctx, SimpleNamespace(query_params={'cursor': first['cursor']}))
    assert 'error' not in activity and activity['batch']['receivedCount'] == 1
    for index in range(21, 46):
        insert_record(index)
    burst = dashboard.get_activity(ctx, SimpleNamespace(query_params={'cursor': activity['cursor']}))
    assert 'error' not in burst and burst['batch']['receivedCount'] == 25
    assert len(burst['events']) <= 20
    with sync_query.connect() as db:
        db.execute('INSERT INTO workflow_stats VALUES(?,?,?,?,?)', ('stream_alert_denoise', 1, 1, 0, 1790121600000))
        db.execute('INSERT INTO workflow_executions VALUES(?,?,?,?,?,?,?,?)',
            ('wf-test', 'stream_alert_denoise', 'success', 1790121600000, 1790121600100, 1790121600100, '{}', json.dumps({'large': 'x' * 300000})))
    snapshot = {}
    events = dashboard._read_workflow_recent_events('stream_alert_denoise', 0, 0, 10, snapshot)
    assert len(events) == 1 and 'large' not in str(events)
    center = dashboard.get_task_center(ctx, SimpleNamespace(query_params={}))
    assert center['sourceStatus']['workflowAvailable'] is True
    assert len(center['workflows']) == 1


def test_task_center_aggregates_real_schedulers_and_empty_history(dashboard):
    from datetime import datetime, timezone
    from flocks.task.store import _TASKS_DDL

    now = datetime.now(timezone.utc).isoformat()
    with sync_query.connect() as db:
        db.execute(_TASKS_DDL)
        db.executemany('INSERT INTO task_schedulers(id,title,trigger,created_at,updated_at) VALUES(?,?,?,?,?)',
            [('scheduler-1', 'First', '{}', now, now), ('scheduler-2', 'Empty', '{}', now, now)])
        db.executemany('INSERT INTO task_executions(id,scheduler_id,title,status,session_id,created_at,updated_at) VALUES(?,?,?,?,?,?,?)',
            [('execution-1', 'scheduler-1', 'One', 'completed', 'session-1', now, now),
             ('execution-2', 'scheduler-1', 'Two', 'running', 'session-2', now, now)])
    result = dashboard.get_task_center(SimpleNamespace(database=sync_query), SimpleNamespace(query_params={}))
    assert result['sessionCount'] == 2
    tasks = {item['id']: item for item in result['scheduledTasks']}
    assert tasks['scheduler-1']['executionCount'] == 2
    assert tasks['scheduler-1']['todayExecutionCount'] == 2
    assert tasks['scheduler-1']['successCount'] == 1
    assert tasks['scheduler-1']['activeCount'] == 1
    assert tasks['scheduler-2']['executionCount'] == 0


def test_workflow_center_batches_many_workflows_and_bounds_payloads(dashboard, monkeypatch):
    import time
    now = int(time.time() * 1000)
    with sync_query.connect() as db:
        db.execute('CREATE TABLE workflow_configs(workflow_id TEXT, kind TEXT, config TEXT, PRIMARY KEY(workflow_id,kind))')
        db.executemany('INSERT INTO workflow_stats VALUES(?,?,?,?,?)', [(f'workflow-{i:02d}', 1, 0, 0, now+i) for i in range(40)])
        db.executemany('INSERT INTO workflow_executions VALUES(?,?,?,?,?,?,?,?)',
            [(f'exec-{i}', f'workflow-{i:02d}', 'running', now+i, now+i, None, '{}', json.dumps({'large':'x'*300000})) for i in range(40)])
        db.execute('INSERT INTO workflow_configs VALUES(?,?,?)', ('workflow-00','workflow_kafka_config',json.dumps({'enabled':False})))
    calls = []
    original = sync_query.Connection.execute
    def execute(db, sql, params=()):
        calls.append(sql)
        return original(db, sql, params)
    monkeypatch.setattr(sync_query.Connection, 'execute', execute)
    result, total, today, active = dashboard._task_center_workflow_rows()
    assert len(result) == 12 and total == today == 40 and active == 39
    assert len(calls) < 20
    assert all(item['latestAlertName'] == '' for item in result)


def test_daily_workflow_samples_preserve_baseline_and_reset_semantics(dashboard):
    with sync_query.connect() as db:
        db.execute(f'CREATE TABLE {dashboard.WORKFLOW_SNAPSHOT_TABLE} '
                   '(workflow_id TEXT, sampled_at BIGINT, call_count BIGINT, PRIMARY KEY(workflow_id,sampled_at))')
        db.executemany(f'INSERT INTO {dashboard.WORKFLOW_SNAPSHOT_TABLE} VALUES(?,?,?)',
            [('idle', 90, 10), ('reset', 90, 10), ('reset', 110, 13),
             ('reset', 120, 2), ('reset', 130, 4), ('no-baseline', 110, 8)])
        assert dashboard._workflow_daily_count_map(db, 100, 200) == {'idle': 0, 'reset': 7}
